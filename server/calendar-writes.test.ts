import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { test } from "node:test";
import { google, type calendar_v3 } from "googleapis";
import type { CalendarEvent } from "../shared/calendar.js";

test("explicit Google writes use deterministic identity, exact notification payloads and safe unknown reconciliation", { timeout: 60000 }, async (t) => {
  const directory = mkdtempSync(path.join(tmpdir(), "emc2-calendar-writes-"));
  Object.assign(process.env, { MAIL_DATA_DIR: directory, MAIL_CONFIG_PATH: path.join(directory, "absent.env"), MAIL_DATA_KEY: Buffer.alloc(32, 44).toString("base64"), GOOGLE_CLIENT_ID: "synthetic-client", GOOGLE_CLIENT_SECRET: "synthetic-secret" });
  const store = await import("./store.js");
  const writer = await import("./google-calendar.js");
  for (const id of ["a", "b"]) { store.put("account", id, { id, email: `${id}@example.test`, provider: "gmail", credentials: { refreshToken: `synthetic-${id}` } }); writer.saveCalendarAccess(id, writer.calendarScopes.join(" "), true); }
  const gmail = google.gmail("v1"), api = google.calendar("v3");
  let identity = "a@example.test";
  const tokens: string[] = [];
  t.mock.method(google, "gmail", (options: any) => { tokens.push(options.auth.credentials.refresh_token); return gmail; }, {});
  t.mock.method(gmail.users, "getProfile", async (_params: unknown, options: any) => { assert.equal(options.retry, false); assert.equal(options.timeout, 10000); return { data: { emailAddress: identity } }; });
  t.mock.method(google, "calendar", () => api, {});
  const inserts: any[] = [], patches: any[] = [], gets: any[] = [];
  let insertFailure = false, patchFailure = false;
  let remote: calendar_v3.Schema$Event = {};
  t.mock.method(api.events, "insert", async (params: calendar_v3.Params$Resource$Events$Insert, options: any) => {
    inserts.push(structuredClone(params)); assert.equal(options.retry, false); assert.equal(options.timeout, 10000);
    remote = { ...params.requestBody, id: params.requestBody!.id, iCalUID: "created@example.test", organizer: { email: identity }, etag: '"created"', attendees: params.requestBody!.attendees, updated: "2026-10-21T12:00:00Z" };
    if (insertFailure) throw new Error("PRIVATE-PROVIDER-BODY");
    return { data: remote };
  });
  t.mock.method(api.events, "get", async (params: any, options: any) => { gets.push(params); assert.equal(options.retry, false); assert.equal(options.timeout, 10000); return { data: structuredClone(remote) }; });
  t.mock.method(api.events, "patch", async (params: any, options: any) => {
    patches.push(structuredClone(params)); assert.equal(options.retry, false); assert.equal(options.headers["If-Match"], remote.etag);
    if (patchFailure) throw { response: { status: 412, data: "PRIVATE-PROVIDER-BODY" } };
    remote = { ...remote, attendees: params.requestBody.attendees, etag: '"next"' };
    return { data: structuredClone(remote) };
  });
  const local: CalendarEvent = { id: randomUUID(), source: "local", accountId: "a", title: "PRIVATE-CALENDAR-WRITE", start: "2026-10-22T15:00:00.000Z", end: "2026-10-22T15:30:00.000Z", allDay: false, attendees: [{ email: "guest@example.test" }, { email: "a@example.test" }], description: "Synthetic notes", location: "Room 2", revision: 1, updatedAt: 1 };
  store.put("calendarEvent", local.id, local);
  try {
    assert.equal(inserts.length, 0); assert.equal(patches.length, 0);
    const first = await writer.createGoogleMeeting("a", local.id, 1);
    assert.equal(first.state, "complete"); assert.equal(inserts.length, 1);
    const inserted = inserts[0];
    assert.equal(inserted.sendUpdates, "all"); assert.equal(inserted.conferenceDataVersion, 1); assert.equal(inserted.calendarId, "primary");
    assert.match(inserted.requestBody.id, /^[0-9a-v]{5,1024}$/);
    assert.match(inserted.requestBody.conferenceData.createRequest.requestId, /^[0-9a-f]{64}$/);
    assert.deepEqual(inserted.requestBody.conferenceData.createRequest.conferenceSolutionKey, { type: "hangoutsMeet" });
    assert.deepEqual(inserted.requestBody.attendees, [{ email: "guest@example.test" }]);
    assert.deepEqual(inserted.requestBody.start, { dateTime: local.start });
    assert.equal((await writer.createGoogleMeeting("a", local.id, 1)).id, first.id); assert.equal(inserts.length, 1);
    await assert.rejects(writer.createGoogleMeeting("b", local.id, 1), /identity changed/);
    assert.equal(inserts.length, 1);
    store.put("calendarEvent", local.id, { ...local, title: "Changed", revision: 2 });
    await assert.rejects(writer.createGoogleMeeting("a", local.id, 2), /different version/);
    const uncertain = { ...local, id: randomUUID() }; store.put("calendarEvent", uncertain.id, uncertain);
    insertFailure = true;
    const unknown = await writer.createGoogleMeeting("a", uncertain.id, 1); assert.equal(unknown.state, "unknown"); assert.equal(inserts.length, 2);
    assert.equal((await writer.createGoogleMeeting("a", uncertain.id, 1)).state, "unknown"); assert.equal(inserts.length, 2);
    const originalConnection = store.get("googleCalendar", "a")!;
    const readsBeforeRevocation = gets.length;
    store.put("googleCalendar", "a", { ...originalConnection, access: false });
    await assert.rejects(writer.createGoogleMeeting("a", uncertain.id, 1, true), /Connect Google Calendar/);
    assert.equal(gets.length, readsBeforeRevocation);
    store.put("googleCalendar", "a", originalConnection);
    store.put("calendarEvent", uncertain.id, { ...uncertain, accountId: "b", revision: 2 });
    identity = "b@example.test";
    await assert.rejects(writer.createGoogleMeeting("b", uncertain.id, 2), /another account/);
    await assert.rejects(writer.createGoogleMeeting("b", uncertain.id, 2, true), /another account/);
    assert.equal(inserts.length, 2); assert.equal(gets.length, readsBeforeRevocation);
    identity = "a@example.test";
    store.put("calendarEvent", uncertain.id, { ...uncertain, title: "Edited after unknown submission", start: "2026-10-23T15:00:00.000Z", end: "2026-10-23T15:30:00.000Z", revision: 2 });
    await assert.rejects(writer.createGoogleMeeting("a", uncertain.id, 2), /different version/);
    const operationMarker = remote.extendedProperties!.private!.emc2Operation;
    remote.extendedProperties!.private!.emc2Operation = "foreign-operation";
    assert.equal((await writer.createGoogleMeeting("a", uncertain.id, 2, true)).state, "unknown");
    remote.extendedProperties!.private!.emc2Operation = operationMarker;
    const recovered = await writer.createGoogleMeeting("a", uncertain.id, 2, true);
    assert.equal(recovered.state, "complete"); assert.equal(inserts.length, 2); assert.equal(gets.at(-1)?.eventId, unknown.remoteId);
    assert.equal(recovered.input, unknown.input); assert.equal(recovered.revision, 1);
    assert.equal(recovered.result?.title, uncertain.title); assert.equal(recovered.result?.start, uncertain.start);
    assert.deepEqual(recovered.result?.attendees.map(person => person.email), ["guest@example.test"]);
    assert.equal(store.get("calendarEvent", uncertain.id)?.title, "Edited after unknown submission");
    await assert.rejects(writer.createGoogleMeeting("a", uncertain.id, 2), /different version/);
    assert.equal(inserts.length, 2);
    insertFailure = false;
    const other = { email: "other@example.test", responseStatus: "tentative", displayName: "Other", optional: true, comment: "Keep this" };
    remote = { id: "incoming", iCalUID: "incoming@example.test", organizer: { email: "organizer@example.test" }, etag: '"fresh"', summary: "Incoming", start: { dateTime: local.start }, end: { dateTime: local.end }, attendees: [{ email: identity, self: true, responseStatus: "needsAction", additionalGuests: 2 }, other] };
    const cached = writer.googleEvent(remote, "a", { id: "primary", name: "Google Calendar", selected: true })!;
    const from = "2026-10-01T00:00:00.000Z", to = "2026-11-01T00:00:00.000Z";
    store.put("googleCalendarWindow", writer.calendarWindowId("a", from, to), { accountId: "a", from, to, events: [cached], syncedAt: 1, stale: false });
    const requestId = randomUUID();
    const answer = await writer.googleRSVP("a", cached, "accepted", requestId);
    assert.equal(answer.state, "complete"); assert.equal(patches.length, 1);
    assert.equal(patches[0].sendUpdates, "all"); assert.equal(patches[0].eventId, "incoming");
    assert.deepEqual(Object.keys(patches[0].requestBody), ["attendees"]);
    assert.deepEqual(patches[0].requestBody.attendees[1], other);
    assert.deepEqual(patches[0].requestBody.attendees[0], { email: identity, self: true, responseStatus: "accepted", additionalGuests: 2 });
    assert.equal(store.get("googleCalendarWindow", writer.calendarWindowId("a", from, to))?.events[0].myResponse, "accepted");
    await writer.googleRSVP("a", cached, "accepted", requestId); assert.equal(patches.length, 1);
    await assert.rejects(writer.googleRSVP("a", cached, "declined", requestId), /different details/);
    identity = "b@example.test"; await assert.rejects(writer.googleRSVP("a", cached, "declined", randomUUID()), /identity changed/); identity = "a@example.test";
    remote.attendeesOmitted = true; await assert.rejects(writer.googleRSVP("a", cached, "declined", randomUUID()), /identity or attendee/); remote.attendeesOmitted = false;
    remote.iCalUID = "foreign@example.test"; await assert.rejects(writer.googleRSVP("a", cached, "declined", randomUUID()), /identity or attendee/); remote.iCalUID = cached.uid;
    assert.equal(patches.length, 1);
    patchFailure = true;
    const failingId = randomUUID();
    const conflict = await writer.googleRSVP("a", cached, "declined", failingId); assert.equal(conflict.state, "unknown"); assert.equal(patches.length, 2);
    await writer.googleRSVP("a", cached, "declined", failingId); assert.equal(patches.length, 2);
    await assert.rejects(writer.googleRSVP("a", cached, "tentative", randomUUID()), /unknown outcome/);
    assert.equal((await writer.googleRSVP("a", cached, "declined", failingId, true)).state, "unknown"); assert.equal(patches.length, 2);
    remote.attendees![0].responseStatus = "declined";
    assert.equal((await writer.googleRSVP("a", cached, "declined", failingId, true)).state, "complete"); assert.equal(patches.length, 2);
    assert.equal(tokens.every((token) => token.startsWith("synthetic-")), true);
    for (const suffix of ["", "-wal"]) assert.equal(readFileSync(path.join(directory, `mail.sqlite${suffix}`)).includes(Buffer.from("PRIVATE-CALENDAR-WRITE")), false);
    assert.doesNotMatch(JSON.stringify(store.all("calendarOperation")), /PRIVATE-PROVIDER-BODY/);
  } finally { rmSync(directory, { recursive: true, force: true }); }
});
