import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { test } from "node:test";
import { google } from "googleapis";
import { simpleParser } from "mailparser";
import type { Draft, Mail } from "../shared/types.js";
import type { CalendarEvent } from "../shared/calendar.js";
import type { Invitation } from "../shared/invitations.js";
import { quietGmailRevision, quietImapWatch } from "./imap-watch-fixture.js";

test("reviewed calendar drafts preserve MIME, identity, revisions, idempotency and encrypted recovery", { timeout: 60000 }, async (t) => {
  const directory = mkdtempSync(path.join(tmpdir(), "emc2-invitations-"));
  Object.assign(process.env, { MAIL_DATA_DIR: directory, MAIL_CONFIG_PATH: path.join(directory, "absent.env"), MAIL_DATA_KEY: Buffer.alloc(32, 43).toString("base64"), MAIL_DESKTOP_TOKEN: "synthetic-invitations", TYPESAFE_API_KEY: "", OPENAI_API_KEY: "" });
  const store = await import("./store.js");
  const { parse, providers, calendarMime, sendSchema } = await import("./providers.js");
  const codec = await import("./ical.js");
  const drafts = await import("./drafts.js");
  const invitations = await import("./invitations.js");
  const backend = await import("./index.js");
  for (const id of ["a", "b"]) store.put("account", id, { id, email: `${id}@example.test`, provider: "gmail", credentials: { refreshToken: `synthetic-${id}` } });
  const server = await backend.startServer(0, undefined, undefined, undefined, quietImapWatch, quietGmailRevision);
  const address = server.address(); assert.ok(address && typeof address === "object");
  const origin = `http://127.0.0.1:${address.port}`;
  const headers = { "X-Desktop-Token": "synthetic-invitations", "Content-Type": "application/json" };
  const { csrf } = await (await fetch(`${origin}/api/state`, { headers })).json() as { csrf: string };
  const request = (route: string, method = "GET", body?: unknown) => fetch(`${origin}/api${route}`, { method, headers: { ...headers, "X-CSRF-Token": csrf }, body: body === undefined ? undefined : JSON.stringify(body) });
  const api = google.gmail("v1"); let sends = 0; let outgoing = Buffer.alloc(0);
  t.mock.method(google, "gmail", () => api, {});
  t.mock.method(api.users.messages, "send", async (params: any) => { sends++; outgoing = Buffer.from(params.requestBody.raw, "base64url"); return { data: {} }; });
  const input = { title: "SYNTHETIC-PRIVATE meeting", start: "2026-10-22T15:00:00.000Z", end: "2026-10-22T15:30:00.000Z", allDay: false, accountId: "a", attendees: ["one@example.test", "two@example.test"], location: "Room 2", description: "Synthetic notes" };
  try {
    const event = await (await request("/calendar/events", "POST", input)).json() as CalendarEvent;
    assert.equal(sends, 0);
    const route = `/calendar/events/${event.id}/invitation`;
    const prepare = () => request(route, "POST", { revision: 1, method: "REQUEST" });
    const [first, duplicate] = await Promise.all([prepare(), prepare()]);
    assert.equal(first.status, 200); assert.equal(duplicate.status, 200);
    const draft = await first.json() as Draft;
    assert.equal((await duplicate.json() as Draft).id, draft.id); assert.equal(store.all("draft").length, 1); assert.equal(sends, 0);
    assert.equal(draft.invitation?.method, "REQUEST"); assert.equal(draft.invitation?.sequence, 0);
    assert.equal((await request(`/accounts/b/drafts/${draft.id}`)).status, 404);
    const { id: _id, accountId: _account, revision: _rev, updatedAt: _time, calendarContext: _context, ...content } = draft;
    assert.equal((await request("/accounts/a/drafts", "POST", content)).status, 400, "Untrusted callers cannot manufacture calendar metadata");
    assert.equal((await request(`/accounts/a/drafts/${draft.id}`, "PUT", { ...content, to: "intruder@example.test", revision: 1 })).status, 409);
    const saved = await (await request(`/accounts/a/drafts/${draft.id}`, "PUT", { ...content, body: "Reviewed invitation body", sendUnknown: true, revision: 1 })).json() as Draft;
    assert.equal(saved.revision, 2); assert.deepEqual(saved.invitation, draft.invitation); assert.deepEqual(saved.calendarContext, draft.calendarContext);
    const send = { ...saved, calendarDraft: { id: saved.id, revision: saved.revision } };
    assert.equal((await request("/send", "POST", send)).status, 200); assert.equal(sends, 1);
    const decoded = await simpleParser(outgoing);
    const calendar = decoded.attachments.find((part) => part.contentType === "text/calendar")!;
    assert.ok(calendar);
    assert.match(outgoing.toString(), /text\/calendar;[^\r\n]*method=REQUEST/i);
    const roundtrip = codec.parseICalendar(calendar.content.toString()); assert.equal(roundtrip.status, "ok");
    if (roundtrip.status === "ok") assert.deepEqual(roundtrip.invitation, saved.invitation);
    assert.equal(decoded.text?.trim(), "Reviewed invitation body");
    await assert.rejects(calendarMime(store.get("account", "b")!, sendSchema.parse(send)), /changed/);
    assert.equal((await prepare()).status, 200, "Unknown send state never creates another invitation draft");
    assert.equal(store.all("draft").length, 1); assert.equal(store.get("draft", draft.id)?.sendUnknown, true);
    const changed = await (await request(`/calendar/events/${event.id}`, "PATCH", { ...input, title: "Updated meeting", revision: 1 })).json() as CalendarEvent;
    assert.equal(changed.revision, 2); assert.equal(changed.uid, saved.invitation?.uid);
    await assert.rejects(calendarMime(store.get("account", "a")!, sendSchema.parse(send)), /event changed/);
    const update = await (await request(route, "POST", { revision: 2, method: "REQUEST" })).json() as Draft;
    const cancel = await (await request(route, "POST", { revision: 2, method: "CANCEL" })).json() as Draft;
    assert.equal(update.invitation?.uid, draft.invitation?.uid); assert.equal(update.invitation?.sequence, 1);
    assert.equal(cancel.invitation?.uid, draft.invitation?.uid); assert.equal(cancel.invitation?.sequence, 2); assert.equal(cancel.invitation?.method, "CANCEL");
    assert.equal((await request(route, "POST", { revision: 1, method: "REQUEST" })).status, 409);
    store.put("draft", update.id, { ...update, sendUnknown: true });
    await assert.rejects(calendarMime(store.get("account", "a")!, sendSchema.parse({ ...update, calendarDraft: { id: update.id, revision: update.revision } })), /event changed/, "A prepared cancellation supersedes the older request at the same event revision");
    await request(`/calendar/events/${event.id}`, "PATCH", { ...input, revision: 2 });
    const afterCancel = await (await request(route, "POST", { revision: 3, method: "REQUEST" })).json() as Draft;
    assert.ok(afterCancel.invitation!.sequence > cancel.invitation!.sequence, "New requests advance beyond an already prepared cancellation");
    const none = await (await request("/calendar/events", "POST", { ...input, accountId: undefined })).json() as CalendarEvent;
    const noAccount = await request(`/calendar/events/${none.id}/invitation`, "POST", { revision: 1, method: "REQUEST" });
    assert.equal(noAccount.status, 409); assert.match(await noAccount.text(), /Choose a connected account/);

    const invite: Invitation = { uid: "incoming@example.test", sequence: 2, method: "REQUEST", organizer: "organizer@example.test", attendees: [{ email: "A@example.test", response: "NEEDS-ACTION" }, { email: "guest@example.test", response: "TENTATIVE" }], title: "SYNTHETIC-INCOMING meeting", start: input.start, end: input.end, allDay: false };
    const raw = (value: string, sender = invite.organizer) => Buffer.from(`From: ${sender}\r\nTo: a@example.test\r\nSubject: Incoming invitation\r\nMessage-ID: <invite@example.test>\r\nMIME-Version: 1.0\r\nContent-Type: text/calendar; charset=utf-8; method=REQUEST\r\n\r\n${value}`);
    const incoming = await parse(store.get("account", "a")!, "incoming", raw(codec.generateICalendar(invite, { stamp: input.start })), false);
    assert.equal(incoming.invitation?.status, "ok");
    const mail: Mail = { ...incoming, category: "important", relevance: 3, reason: "Synthetic", archived: false, snoozedUntil: null };
    store.put("mail", mail.id, mail);
    const invitationRoute = `/calendar/invitations/${encodeURIComponent(mail.id)}`;
    const identity = await (await request(invitationRoute)).json() as { fingerprint: string; eligible: boolean };
    assert.equal(identity.eligible, true);
    const replyInput = { fingerprint: identity.fingerprint, response: "ACCEPTED" };
    const reply = await (await request(`${invitationRoute}/reply`, "POST", replyInput)).json() as Draft;
    const replay = await (await request(`${invitationRoute}/reply`, "POST", replyInput)).json() as Draft;
    assert.equal(reply.id, replay.id); assert.equal(reply.to, invite.organizer); assert.equal(reply.accountId, "a");
    assert.deepEqual(reply.invitation?.attendees, [{ email: "A@example.test", response: "ACCEPTED" }]); assert.equal(reply.invitation?.method, "REPLY");
    const local = store.all("calendarEvent").find((item) => item.uid === invite.uid)!;
    assert.equal(local.accountId, "a"); assert.equal(local.myResponse, "accepted"); assert.equal(sends, 1);
    assert.equal((await request(`${invitationRoute}/reply`, "POST", { ...replyInput, event: input })).status, 400);
    store.put("mail", mail.id, { ...mail, accountId: "b" });
    assert.equal((await request(`${invitationRoute}/reply`, "POST", replyInput)).status, 409);
    store.put("mail", mail.id, { ...mail, address: "spoof@example.test" });
    assert.equal((await request(`${invitationRoute}/reply`, "POST", replyInput)).status, 409);
    store.put("mail", mail.id, mail);
    const { id: replyId, accountId: _replyAccount, revision: _replyRevision, updatedAt: _replyTime, calendarContext: _replyContext, ...replyContent } = reply;
    const editedResponse = await request(`/accounts/a/drafts/${replyId}`, "PUT", { ...replyContent, body: "Reviewed RSVP body", revision: 1 });
    assert.equal(editedResponse.status, 200, "A prepared REPLY must remain editable");
    const edited = await editedResponse.json() as Draft;
    const markedResponse = await request(`/accounts/a/drafts/${replyId}`, "PUT", { ...replyContent, body: edited.body, sendUnknown: true, revision: edited.revision });
    assert.equal(markedResponse.status, 200, "Ordinary Send must persist uncertainty first");
    const marked = await markedResponse.json() as Draft;
    const replySend = { ...marked, calendarDraft: { id: marked.id, revision: marked.revision } };
    const receiving = store.get("account", "a")!;
    store.put("account", "a", { ...receiving, email: "wrong@example.test" });
    await assert.rejects(calendarMime(store.get("account", "a")!, sendSchema.parse(replySend)), /another account/);
    store.put("account", "a", receiving);
    assert.equal((await request("/send", "POST", replySend)).status, 200); assert.equal(sends, 2);
    const replyMime = await simpleParser(outgoing);
    const replyCalendar = replyMime.attachments.find((part) => part.contentType === "text/calendar")!;
    assert.match(outgoing.toString(), /text\/calendar;[^\r\n]*method=REPLY/i);
    const replyRoundtrip = codec.parseICalendar(replyCalendar.content.toString());
    assert.equal(replyRoundtrip.status, "ok");
    if (replyRoundtrip.status === "ok") assert.deepEqual(replyRoundtrip.invitation, reply.invitation);
    assert.equal(replyMime.text?.trim(), "Reviewed RSVP body");
    assert.equal(store.get("draft", reply.id)?.sendUnknown, true);
    const cancelled: Mail = { ...mail, id: "a:cancel", remoteId: "cancel", invitation: { status: "ok", invitation: { ...invite, method: "CANCEL", sequence: 3 } } };
    store.put("mail", cancelled.id, cancelled);
    const cancelIdentity = await (await request(`/calendar/invitations/${encodeURIComponent(cancelled.id)}`)).json() as { fingerprint: string };
    assert.equal((await request(`/calendar/invitations/${encodeURIComponent(cancelled.id)}/apply`, "POST", cancelIdentity)).status, 400, "Only the fingerprint is accepted");
    assert.equal((await request(`/calendar/invitations/${encodeURIComponent(cancelled.id)}/apply`, "POST", { fingerprint: cancelIdentity.fingerprint })).status, 200);
    assert.equal(store.get("calendarEvent", local.id)?.cancelled, true);
    assert.equal((await request(`${invitationRoute}/reply`, "POST", replyInput)).status, 409);
    const unsupported = await parse(store.get("account", "a")!, "recurring", raw(codec.generateICalendar(invite, { stamp: input.start }).replace("END:VEVENT", "RRULE:FREQ=WEEKLY\r\nEND:VEVENT")), false);
    assert.equal(unsupported.invitation?.status, "unsupported");
    const custom = await parse(store.get("account", "a")!, "custom-zone", raw(codec.generateICalendar(invite, { stamp: input.start }).replace("DTSTART:20261022T150000Z", "DTSTART;TZID=Custom/Unknown:20261022T150000")), false);
    assert.equal(custom.invitation?.status, "unsupported");
    const huge = await parse(store.get("account", "a")!, "huge", raw("x".repeat(131073)), false);
    assert.deepEqual(huge.invitation, { status: "invalid", reason: "limit" });
    for (const suffix of ["", "-wal"]) { const bytes = readFileSync(path.join(directory, `mail.sqlite${suffix}`)); assert.equal(bytes.includes(Buffer.from("SYNTHETIC-INCOMING")), false); assert.equal(bytes.includes(Buffer.from("Reviewed invitation body")), false); }
    assert.equal(drafts.readDraft("a", saved.id).sendUnknown, true);
    assert.throws(() => invitations.prepareEventInvitation(none.id, 1, "REQUEST"), /connected account/);
    assert.equal(sends, 2, "Only the two explicitly reviewed ordinary Sends submit mail");
  } finally { await new Promise<void>((resolve) => server.close(() => resolve())); store.closeStore(); rmSync(directory, { recursive: true, force: true }); }
});
